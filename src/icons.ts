export type IconName = keyof typeof ICON_INNER;

/**
 * Encodes an icon as a CSS mask-image data URI. The mask source's own stroke color is
 * irrelevant (masking only reads the rendered alpha), so it's fixed to black; the
 * masked element's `background-color: currentColor` supplies the actual visible color.
 */
export function iconMaskUrl(name: IconName): string {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" ` +
    `stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">` +
    `${ICON_INNER[name]}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}
